    // Generate PaymentID
    private String generatePaymentID() {
        int highestPaymentID = 0;

        try (BufferedReader br = new BufferedReader(new FileReader("C:\\OOP\\bookingrecord.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] parts = line.split(":");
                if (parts.length >= 1) {
                    String paymentID = parts[0];
                    if (paymentID.startsWith("P")) {
                        try {
                            // Extract the numeric part and parse it as an integer
                            int number = Integer.parseInt(paymentID.substring(1));
                            highestPaymentID = Math.max(highestPaymentID, number);
                        } catch (NumberFormatException e) {
                        // Handle any line that doesn't have a valid number after the "P"
                        }
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error reading booking records: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

        // Return the next PaymentID with the "P" prefix and zero-padded number
        return String.format("P%02d", highestPaymentID + 1); // Example: P01, P02, P03
    }

    
