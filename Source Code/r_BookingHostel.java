    private void loadRoomTypes() {
        try (BufferedReader reader = new BufferedReader(new FileReader("C:\\OOP\\fees.txt"))) {
            DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
            List<String> roomTypeList = new ArrayList<>();
            List<String> feeList = new ArrayList<>();
            String line;

            while ((line = reader.readLine()) != null) {
                String[] parts = line.split(":");
                if (parts.length == 2) {
                    roomTypeList.add(parts[0]); // Add room type
                    feeList.add(parts[1]); // Add corresponding fee
                }
            }

            // Convert lists to arrays
            roomTypes = roomTypeList.toArray(new String[0]);
            fees = feeList.toArray(new String[0]);

            // Set ComboBox model with room types
            model.addAll(roomTypeList);
            roomtype.setModel(model); // Corrected reference to combo box
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading room types: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private String getSelectedPrice(String roomType) {
        // Find the index of the selected room type
        for (int i = 0; i < roomTypes.length; i++) {
            if (roomTypes[i].equals(roomType)) {
                return fees[i]; // Return corresponding fee
            }
        }
        return "Not Found"; // return "Not found" if no match is found
    }

    private void loadFeesTable() {
        try (BufferedReader reader = new BufferedReader(new FileReader("C:\\OOP\\fees.txt"))) {
            String line;
            DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
            model.setColumnIdentifiers(new String[] { "Room Type", "Fee" });
            model.setRowCount(0); // Clear previous rows

            while ((line = reader.readLine()) != null) {
                String[] parts = line.split(":");
                if (parts.length == 2) {
                    model.addRow(parts); // Add row to table
                }
            }
        } catch (Exception e) {
        }
    }

