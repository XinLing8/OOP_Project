    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String paymentID = jTextField1.getText().trim();

        if (paymentID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a PaymentID.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Read the payment records and find the record with the matching PaymentID
        List<String[]> paymentData = readPaymentRecords();
        String[] record = null;

        for (String[] data : paymentData) {
            if (data[0].equals(paymentID)) {
                record = data;
                break;
            }
        }

        if (record != null) {
            // Get the current date and time
            Date currentDate = new Date();
            SimpleDateFormat dateFormat = new SimpleDateFormat("dd/MM/yyyy HH:mm:ss");
            String dateTime = dateFormat.format(currentDate);

            // Get the room type and facilities
            String roomType = record[2];
            int roomFee = getRoomFee(roomType); // Get room fee using the new method

            String facilitiesFee = record[4].equalsIgnoreCase("yes") ? "RM 100" : "RM 0";  // Assuming a fixed facilities fee of RM100

            // Validate and parse the number of months
            int months = 0;
            String paymentDuration = record[3].toLowerCase();

            if (paymentDuration.equals("year")) {
                months = 12;
            } else if (paymentDuration.equals("semester")) {
                months = 4;
            } else if (paymentDuration.equals("month")) {
                months = 1;
            } else {
                try {
                    months = Integer.parseInt(paymentDuration); // If it's a number, parse it directly
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Invalid payment duration.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            // Calculate the total amount
            int totalAmount = (roomFee * months) + 100; // Adding facilities fee (RM100)

            // Print the receipt
            log_UserActivity.logUserActivity(username, "Generate Receipt");
            String receipt = "\n"
                    + "-----------------------------------Receipt------------------------------------\n"
                    + "\n"
                    + "Payment ID: " + paymentID + "               " + "Date & Time: " + dateTime + "\n"
                    + "Username: " + record[1]           
                    + "\n"
                    + "Room Type: " + roomType + "                                             " + "RM "+roomFee + "\n" 
                    + "Payment Duration:                                                            " +"*"+ months + "\n"
                    + "Facilities Fee:                                                           " +facilitiesFee + "\n"
                    + "\n"
                    + "\n"
                    + "*********************************************************************\n"
                    + "                              Total Amount: RM" + totalAmount + "\n"
                    + "*********************************************************************\n"
                    + "\n"
                    + "                         -Thanks for using our system-";
                    

            //Display the receipt in the JTextArea1
            jTextArea1.setText(receipt);
            
            // Mark the payment as completed and update the file
            record[6] = "Paid";
            updatePaymentRecords(paymentData);
        } else {
            JOptionPane.showMessageDialog(this, "Payment record not found.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

