    // Get room fee based on room type
    private int getRoomFee(String roomType) {
        int roomFee = 0;

        // Check the room type and assign corresponding fee
        if (roomType.equalsIgnoreCase("Single(Non-AC)")) {
            roomFee = 600; // Example fee for Single room
        } else if (roomType.equalsIgnoreCase("Single(AC)")) {
            roomFee = 800; // Example fee for Double room
        } else if (roomType.equalsIgnoreCase("Twin(Non-AC)")) {
            roomFee = 500; // Example fee for Suite room
        } else{
            roomFee = 600;
        }

        return roomFee;
    }
    
    private void loadPaymentRecords() {
        // Read the payment records and display all records in the table
        List<String[]> paymentData = readPaymentRecords();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

        // Clear existing rows
        model.setRowCount(0);

        // Set column headers
        model.setColumnIdentifiers(new String[]{"PaymentID", "Username", "Room Type", "Payment Duration", "Facilities Fee", "Total Amount", "Payment Status"});

        // Add all records to the table
        for (String[] record : paymentData) {
            model.addRow(record);
        }
        
        // Make the table non-editable
        for (int i = 0; i < model.getRowCount(); i++) {
            for (int j = 0; j < model.getColumnCount(); j++) {
                jTable1.setDefaultEditor(model.getColumnClass(j), null);  // Disables editing for all cells
            }
        }
    }
    
    private List<String[]> readPaymentRecords() {
        List<String[]> paymentData = new ArrayList<>();
        try (BufferedReader br = new BufferedReader(new FileReader("C:\\OOP\\payments.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] record = line.split(":");
                paymentData.add(record);
            }
        } catch (Exception e) {
        }
        return paymentData;
    }

    
