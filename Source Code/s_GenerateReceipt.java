    private void updatePaymentRecords(List<String[]> paymentData) {
        try (BufferedWriter bw = new BufferedWriter(new FileWriter("C:\\OOP\\payments.txt"))) {
            for (String[] record : paymentData) {
                bw.write(String.join(":", record));
                bw.newLine();
            }
        } catch (Exception e) {
        }
    }
    
