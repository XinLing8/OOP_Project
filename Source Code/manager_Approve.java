    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Validate if username is entered
        String username = jTextField1.getText().trim();
        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a username.");
            return;
        }

        // Search for the user by username in the users.txt file
        boolean userFound = approveUserByUsername(username);

        if (userFound) {
            // Reload the table after approval
            loadUsersTable();
            log_UserActivity.logUserActivity(username, "Approve New User");
            JOptionPane.showMessageDialog(this, "User " + username + " has been approved.");
        } else {
            JOptionPane.showMessageDialog(this, "User not found.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

