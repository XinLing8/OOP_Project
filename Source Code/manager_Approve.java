    private void loadUsersTable() {
        try (BufferedReader reader = new BufferedReader(new FileReader("C:\\OOP\\users.txt"))) {
            String line;

            // Make sure the table is non-editable
            DefaultTableModel model = new DefaultTableModel(new String[] { "Username", "Password", "Role", "Status" }, 0) {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return false; 
                }
            };

            model.setRowCount(0);

            while ((line = reader.readLine()) != null) {
                String[] parts = line.split(":");
                model.addRow(parts);
            }

            jTable2.setModel(model); // Set the table become non-editable
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading users: " + e.getMessage());
        }
    }
    
    private void storeUserInRoleFile(String username, String password, String role) {
        String fileName = "";

        if (role.equals("Manager")) {
            fileName = "C:\\OOP\\manager.txt";
        } else if (role.equals("Staff")) {
            fileName = "C:\\OOP\\staff.txt";
        } else if (role.equals("Resident")) {
            fileName = "C:\\OOP\\residents.txt";
        }

        try (BufferedWriter bw = new BufferedWriter(new FileWriter(fileName, true))) {
            bw.write(username + ":" + password + "\n");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving user to role file: " + e.getMessage());
        }
    }
    
    private boolean approveUserByUsername(String username) {
        File inputFile = new File("C:\\OOP\\users.txt");
        StringBuilder updatedContent = new StringBuilder();
        boolean userFound = false;

        try (BufferedReader reader = new BufferedReader(new FileReader(inputFile))) {
            String line;
            while ((line = reader.readLine()) != null) {
                String[] parts = line.split(":");
                if (parts[0].equals(username)) {
                    // User found, update status to "Approved"
                    line = parts[0] + ":" + parts[1] + ":" + parts[2] + ":Approved";
                    userFound = true;

                    // Store the user in the appropriate role-based file
                    storeUserInRoleFile(parts[0], parts[1], parts[2]);
                }

                // Add the (updated or unchanged) line to the new content (excluding approved user)
                if (!line.startsWith(username)) {
                    updatedContent.append(line).append("\n");
                }
            }

            if (userFound) {
                // Overwrite the original users.txt file with the updated content (excluding approved user)
                try (BufferedWriter bw = new BufferedWriter(new FileWriter(inputFile))) {
                    bw.write(updatedContent.toString());
                }
            }
        } catch (Exception e) {
    }

    return userFound;
}

    
    
