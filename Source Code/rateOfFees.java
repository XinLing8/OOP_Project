    private void loadRoomTypes() {
        try (BufferedReader reader = new BufferedReader(new FileReader("C:\\OOP\\fees.txt"))) {
            DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
            String line;

            while ((line = reader.readLine()) != null) {
                model.addElement(line.split(":")[0]); // Extract room type
            }

            roomtype.setModel(model);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading room types: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadFeesTable() {
        try (BufferedReader br = new BufferedReader(new FileReader("C:\\OOP\\fees.txt"))) {
            String line;
            DefaultTableModel model = (DefaultTableModel) loadFeesTable.getModel();
            model.setColumnIdentifiers(new String[] { "Room Type", "Fee" }); // Add column headers as room type and fee

            model.setRowCount(0); // Clear existing rows

            while ((line = br.readLine()) != null) {
                String[] parts = line.split(":");
                model.addRow(parts); // Add room type and fee as a row
            }
            
            // Make sure the table is non-editable
            DefaultTableModel nonEditableModel = new DefaultTableModel() {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return false; 
                }
            };
            
                    for (int i = 0; i < model.getColumnCount(); i++) {
            nonEditableModel.addColumn(model.getColumnName(i));
        }
            for (int i = 0; i < model.getRowCount(); i++) {
                Object[] row = new Object[model.getColumnCount()];
                for (int j = 0; j < model.getColumnCount(); j++) {
                    row[j] = model.getValueAt(i, j);
                }
                nonEditableModel.addRow(row);
            }
            loadFeesTable.setModel(nonEditableModel);
        
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading fees: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void updateFeeInFile(String roomType, double newFee) {
        java.util.List<String> lines = new java.util.ArrayList<>();  
        
        try (BufferedReader reader = new BufferedReader(new FileReader("C:\\OOP\\fees.txt"))) {
            String line;
            boolean feeUpdated = false;
    
            // Read the current data
            while ((line = reader.readLine()) != null) {
                // Check if the line contains the selected room type
                if (line.startsWith(roomType)) {
                    // Update the fee for the selected room type
                    lines.add(roomType + ":" + newFee);
                    feeUpdated = true;
                } else {
                    lines.add(line); // Keep the existing lines unchanged
                }
            }
    
            // If the fee for the room type was not found, add it as a new entry
            if (!feeUpdated) {
                lines.add(roomType + ":" + newFee);
            }
    
        } catch (Exception e) {
        }

        // Write the updated data back to the file
        try (BufferedWriter bw = new BufferedWriter(new FileWriter("C:\\OOP\\fees.txt"))) {
            for (String line : lines) {
                bw.write(line);
                bw.newLine();
            }
        } catch (Exception e) {
        }
    }

    
    
