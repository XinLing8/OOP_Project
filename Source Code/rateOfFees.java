    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Get selected room type
        String selectedRoomType = (String) roomtype.getSelectedItem();
        if (selectedRoomType == null) {
            JOptionPane.showMessageDialog(this, "Please select a room type.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate new fee input
        String newFeeText = jTextField1.getText().trim();
        if (newFeeText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a new fee.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            double newFee = Double.parseDouble(newFeeText);
            // Update fee in file and reload table
            updateFeeInFile(selectedRoomType, newFee);
            loadFeesTable();
            String username = LoginManager.getCurrentUser();
            log_UserActivity.logUserActivity(username, "Update Rate of Fees");
            JOptionPane.showMessageDialog(this, "Fee updated successfully!");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid fee. Please enter a number.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

