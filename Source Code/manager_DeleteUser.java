    private void loadData() {
        String[] files = {"C:\\OOP\\manager.txt", "C:\\OOP\\staff.txt", "C:\\OOP\\residents.txt"};

        // Make sure the table is non-editable
        tableModel = new DefaultTableModel(new Object[][] {}, new String[] { "Username", "Password" }) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;  // Prevent editing
            }
        };

    // Setting the table
    jTable1.setModel(tableModel);

        
    for(String file: files){
        try {
            loadFileData(file);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading user data: " + e.getMessage());
        }        
    }
}
  
    private void loadFileData(String fileName) throws Exception {
        try (BufferedReader br = new BufferedReader(new FileReader(fileName))) {
            String line;
            
            // Read the file line by line and add rows to the model
            while ((line = br.readLine()) != null) {
                String[] parts = line.split(":");
                if (parts.length == 2) {  // Ensure there are exactly two variables: (username and password)
                    tableModel.addRow(parts);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading file data: " + e.getMessage());
        }
    }

    private void deleteFromFile(String fileName, String username) {
        File inputFile = new File(fileName);
        StringBuilder fileContent = new StringBuilder(); // To store file content

        try (BufferedReader br = new BufferedReader(new FileReader(inputFile))) {
            String line;
            boolean found = false;
            while ((line = br.readLine()) != null) {
                if (!line.startsWith(username + ":")) {
                    fileContent.append(line).append(System.lineSeparator());  // Append all non-deleted lines
                } else {
                    found = true;  // Mark as found when matching the user
                }
            }

            // If the username wasn't found, show an error message and return
            if (!found) {
                JOptionPane.showMessageDialog(this, "User not found in file: " + fileName);
                return;
            }

            // Write updated content back to the original file
            try (BufferedWriter bw = new BufferedWriter(new FileWriter(inputFile))) {
                bw.write(fileContent.toString());
            }
            log_UserActivity.logUserActivity(username, "Delete User");
            JOptionPane.showMessageDialog(this, "User deleted successfully from file.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error deleting user: " + e.getMessage());
        }
    }

    
    private String getFileNameForUser(String username) {
        // Get filename for according to role
        if (username.startsWith("Manager_")) {
            return "C:\\OOP\\manager.txt";
        } else if (username.startsWith("Staff_")) {
            return "C:\\OOP\\staff.txt";
        } else {
            return "C:\\OOP\\residents.txt";
        }
    }
    
    private boolean fileExists(String fileName) {
        File f = new File(fileName);
        return f.exists();
    }   

