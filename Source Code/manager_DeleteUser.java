    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = jTextField1.getText();
        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a username to search.");
            return;
        }

        for (int i = 0; i < tableModel.getRowCount(); i++) {
            if (tableModel.getValueAt(i, 0).equals(username)) {
                jTable1.setRowSelectionInterval(i, i);
                return;
            }
        }
        JOptionPane.showMessageDialog(this, "User not found.");                  
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a user to delete.");
            return;
        }

        // Get the username of the selected row
        String username = (String) tableModel.getValueAt(selectedRow, 0);  // Only get the username

        // Show confirmation dialog with the username in the message
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete user " + username + "?",
            "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        
        if (confirm != JOptionPane.YES_OPTION) return;

        // Delete user from the file
        String fileName = getFileNameForUser(username);  // You can use the username to determine the file
        deleteFromFile(fileName, username);

        // After successful file deletion, remove the row from the table
        if (fileExists(fileName)) { // Check if the file is successfully updated
            tableModel.removeRow(selectedRow);
            JOptionPane.showMessageDialog(this, "User deleted successfully.");
            loadData();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update the file. User not deleted.");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

