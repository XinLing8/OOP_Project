    private void s_usernameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_s_usernameActionPerformed
        String username = s_username.getText(); // Get INPUT
        boolean usernameExists = false;

        try {
            FileReader fr = new FileReader("C:\\OOP\\staff.txt");
            BufferedReader br = new BufferedReader(fr);
            String line;

            // Check each line in the file
            while ((line = br.readLine()) != null) {
                if (line.equalsIgnoreCase(username)) { 
                    usernameExists = true;
                    break;
                }
            }

            br.close();
            fr.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error occurs while reading the file: " + e.getMessage());
        }
    }//GEN-LAST:event_s_usernameActionPerformed

