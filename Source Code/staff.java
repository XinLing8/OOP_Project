    private void b_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_loginActionPerformed
        String username = s_username.getText();
        String password = new String(s_password.getPassword());
        boolean isLoginSuccessful = false;

        // Validate inputs
        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill out username");
            return;
        }
        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill out password");
            return;
        }

        // Check credentials in file
        try (BufferedReader br = new BufferedReader(new FileReader("C:\\OOP\\staff.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                // Assume file format: "username:password"
                String[] credentials = line.split(":");
                if (credentials.length == 2) {
                    String fileUsername = credentials[0].trim();
                    String filePassword = credentials[1].trim();
                    if (fileUsername.equals(username) && filePassword.equals(password)) {
                        isLoginSuccessful = true;
                        break;
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error reading file: " + e.getMessage());
            return;
        }

        // Show appropriate message and action
        if (isLoginSuccessful) {
            LoginManager.setCurrentUser(username);
            log_UserActivity.logUserActivity(username, "Login");
            JOptionPane.showMessageDialog(null, "Successful Login!");
            staffMenu_ s = new staffMenu_(); // Proceed to staffMenu
            s.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(null, "Couldn't find your account.", "Login Failed", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_b_loginActionPerformed

