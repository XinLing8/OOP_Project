    private void loadBookingRecords() {
        // Display booking records in a table
        List<String[]> bookingData = readBookingRecords();
        DefaultTableModel model = new DefaultTableModel() {
            // Override isCellEditable method to make the cells non-editable
            @Override
            public boolean isCellEditable(int rowIndex, int columnIndex) {
                return false; // Prevent editing for all cells
            }
        };
        
        // Clear any existing rows
        model.setRowCount(0);

        // Add header with PaymentID, username, roomtype, paymentduration, facilities, and paymentstatus
        model.setColumnIdentifiers(new String[] {"PaymentID", "Username", "Room Type", "Payment Duration", "Facilities Fee", "Payment Status"});

        // Add booking records to the table
        for (String[] record : bookingData) {
            model.addRow(record);
        }
        
        // Set the model for the table
        jTable1.setModel(model);
    }

    private List<String[]> readBookingRecords() {
        List<String[]> bookingData = new ArrayList<>();
        try (BufferedReader br = new BufferedReader(new FileReader(BOOKING_FILE))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] record = line.split(":");
                // Add record to the list
                bookingData.add(record);
            }
        } catch (Exception e) {
        }
        return bookingData;
    }

