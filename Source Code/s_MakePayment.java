    private double getRoomRate(String roomType) {
        // Define rates based on room type
        switch (roomType) {
            case "Single":
                return 600;  // RM200 for a single room
            case "Twin":
                return 500;  // RM300 for a double room
            case "Single(AC)":
                return 800;  // RM200 for a single room
            case "Twin(AC)":
                return 600;
            default:
                return 0;  // Default rate for unknown room types
        }
    }

    private double calculateTotalPayment(double roomRate, String paymentDuration, boolean isFacilitiesFeeIncluded) {
        double durationMultiplier = paymentDuration.equalsIgnoreCase("Year") ? 12 : 1;
        double facilitiesFee = isFacilitiesFeeIncluded ? 100 : 0;
        return (roomRate * durationMultiplier) + facilitiesFee;
    }

    private void saveUpdatedBookingRecords(List<String[]> updatedBookingData) {
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(BOOKING_FILE))) {
            for (String[] record : updatedBookingData) {
                bw.write(String.join(":", record));
                bw.newLine();
            }
        } catch (Exception e) {
        }
    }

    private void savePaymentData(String paymentID, String username, String roomType, String paymentDuration, String facilities, double totalAmount, String paymentStatus) {
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(PAYMENTS_FILE, true))) {
            String record = String.format("%s:%s:%s:%s:%s:%.2f:%s", paymentID, username, roomType, paymentDuration, facilities, totalAmount, paymentStatus);
            bw.write(record);
            bw.newLine();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving payment data. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }



