    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    // Get the PaymentID entered by staff
    String paymentID = jTextField1.getText().trim();

    if (paymentID.isEmpty()) {
        JOptionPane.showMessageDialog(this, "PaymentID cannot be empty. Please enter a valid PaymentID.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    List<String[]> bookingData = readBookingRecords();
    boolean found = false;

    // Variables to hold booking details
    String username = "";
    String roomType = "";
    String paymentDuration = "";
    String facilities = "";
    double totalAmount = 0;

    List<String[]> updatedBookingData = new ArrayList<>();

    for (String[] record : bookingData) {
        if (record[0].equals(paymentID)) { // Match PaymentID
            found = true;

            if (record[5].equalsIgnoreCase("Paid")) {
                JOptionPane.showMessageDialog(this, "This payment has already been made.", "Information", JOptionPane.INFORMATION_MESSAGE);
                return;
            }

            // Extract data
            username = record[1];
            roomType = record[2];
            paymentDuration = record[3];
            facilities = record[4];

            // Validate roomType
            double roomRate = getRoomRate(roomType);
            if (roomRate == 0) {
                JOptionPane.showMessageDialog(this, "Invalid room type in booking records. Please check the data.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Calculate total payment
            boolean isFacilitiesFeeIncluded = facilities.equalsIgnoreCase("yes");
            totalAmount = calculateTotalPayment(roomRate, paymentDuration, isFacilitiesFeeIncluded);

            // Update payment status
            record[5] = "Paid";  // Update payment status to Paid
            updatedBookingData.add(record);

            // Save payment details
            savePaymentData(paymentID, username, roomType, paymentDuration, facilities, totalAmount, "Paid");
            log_UserActivity.logUserActivity(username, "Make Payment");
            JOptionPane.showMessageDialog(this, "Payment successful for PaymentID: " + paymentID + ". Total: RM" + totalAmount, "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            updatedBookingData.add(record); // Keep unchanged records
        }
    }

    if (found) {
        saveUpdatedBookingRecords(updatedBookingData); // Save updated booking records
        loadBookingRecords(); // Refresh table
    } else {
        JOptionPane.showMessageDialog(this, "PaymentID not found in the booking records. Please check and try again.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

