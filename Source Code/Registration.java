    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String enteredUsername = username.getText();
        String password = new String(this.password.getPassword()); // Get password
        String confirmPassword = new String(c_password.getPassword()); // Get confirm password
        String role = (String) jComboBox1.getSelectedItem();
        String status = "Pending"; // Set status to "Pending"

        // Validate username prefix
        String prefix = role + "_";
        if (!enteredUsername.startsWith(prefix)) {
            JOptionPane.showMessageDialog(this, "Username must start with '" + prefix + "'.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Check if the username already exists in the file
        boolean usernameExists = false;
        String[] files = {"C:\\OOP\\manager.txt", "C:\\OOP\\staff.txt", "C:\\OOP\\residents.txt", "C:\\OOP\\users.txt"};

        for(String file: files){
            try {
                FileReader fr = new FileReader(file);
                BufferedReader br = new BufferedReader(fr);
                String line;

                while ((line = br.readLine()) != null) {
                    // Assuming the file contains username:password:role:status format
                    String[] parts = line.split(":");
                    String storedUsername = parts[0]; // Extract the stored username
                    if (storedUsername.equalsIgnoreCase(enteredUsername)) {
                        usernameExists = true;
                        break;
                    }
                }

                br.close();
                fr.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error reading the file: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }  

        if (usernameExists) {
            JOptionPane.showMessageDialog(this, "Username already exists! Please choose a different one.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate password
        if (password.length() < 8 || !password.matches(".*[A-Za-z].*") || !password.matches(".*[0-9].*") || !password.matches(".*[^A-Za-z0-9].*")) {
            JOptionPane.showMessageDialog(this, "Password must be at least 8 characters long, with 1 alphabet, 1 number, and 1 symbol.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate confirm password
        if (!password.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(this, "Passwords do not match.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Save to file in format: username:password:role:status
        try (BufferedWriter bw = new BufferedWriter(new FileWriter("C:\\OOP\\users.txt", true))) {
            bw.write(enteredUsername + ":" + password + ":" + role + ":" + status);
            bw.newLine();
            JOptionPane.showMessageDialog(this, "Registration successful!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving user details: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

