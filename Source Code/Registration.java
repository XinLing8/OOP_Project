    private void passwordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_passwordActionPerformed
        String enteredPassword = new String(password.getPassword());  // Get password
        boolean passwordExists = false;

        try {
            FileReader fr = new FileReader("C:\\OOP\\manager.txt");
            BufferedReader br = new BufferedReader(fr);
            String line;

            while ((line = br.readLine()) != null) {
                // Assuming the file contains username,password format
                String[] parts = line.split(",");
                String storedUsername = parts[0];
                String storedPassword = parts[1];

                if (storedUsername.equalsIgnoreCase(username.getText().trim()) && storedPassword.equals(enteredPassword)) {
                    passwordExists = true;
                    break;
                }
            }

            br.close();
            fr.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error occurs while reading the file: " + e.getMessage());
        }

        if (passwordExists) {
            JOptionPane.showMessageDialog(this, "Password exists and matches!");
        } else {
            JOptionPane.showMessageDialog(this, "Password does not exist or does not match!");
        }
    }//GEN-LAST:event_passwordActionPerformed

